#!/bin/sh
#
# Compare the doxygen warning log with docs/doxygen-baseline.txt.
#
# The reference is far from fully documented (see docs/plan/documentation.md),
# so a hard "no warnings" gate would block every change. Instead the baseline
# records how many warnings each file currently produces, and this script fails
# only when a file produces more than the baseline. The baseline may shrink in
# any PR that documents something; growing it is a deliberate, reviewable act.
#
# Usage:
#   docs/check-warnings.sh            check against the baseline
#   docs/check-warnings.sh --update   rewrite the baseline from the current tree

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
VERSION=$(tr -d '[:space:]' < "$ROOT/VERSION.txt")
DOXYGEN=${DOXYGEN:-doxygen}
BASELINE="$ROOT/docs/doxygen-baseline.txt"

UPDATE=0
case "${1:-}" in
    "")
        ;;
    --update)
        UPDATE=1
        ;;
    -h|--help)
        sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
        exit 0
        ;;
    *)
        echo "docs/check-warnings.sh: unknown argument: $1" >&2
        exit 2
        ;;
esac

if ! command -v "$DOXYGEN" >/dev/null 2>&1; then
    echo "docs/check-warnings.sh: doxygen not found: $DOXYGEN" >&2
    exit 1
fi

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM

config="$WORK/check.doxyfile"
cat > "$config" <<EOF
@INCLUDE = $ROOT/Doxyfile
OUTPUT_DIRECTORY = $WORK/out
GENERATE_HTML = NO
QUIET = YES
WARN_LOGFILE = $WORK/warnings.log
EOF

( cd "$ROOT" && AVCPP_VERSION="$VERSION" "$DOXYGEN" "$config" >/dev/null 2>&1 || true )

if [ ! -f "$WORK/warnings.log" ]; then
    echo "docs/check-warnings.sh: doxygen produced no warning log" >&2
    exit 1
fi

# One line per file: "<path>\t<count>". Only the first line of a warning counts;
# doxygen continues some warnings with indented detail lines.
grep -E ':[0-9]+: warning:' "$WORK/warnings.log" \
    | sed -E "s#^$ROOT/##; s#:[0-9]+: warning:.*##" \
    | sort \
    | uniq -c \
    | awk '{ printf "%s\t%d\n", $2, $1 }' \
    | sort > "$WORK/current.txt"

total_current=$(awk -F'\t' '{ s += $2 } END { printf "%d", s + 0 }' "$WORK/current.txt")

if [ "$UPDATE" = 1 ]; then
    {
        echo "# Doxygen warning baseline: warnings per file."
        echo "#"
        echo "# Generated by \`docs/check-warnings.sh --update\`; do not edit by hand."
        echo "# The baseline may only shrink. When a PR documents members or fixes a"
        echo "# warning, regenerate it and commit the smaller numbers with the same PR."
        echo "#"
        echo "# Format: <path> <TAB> <number of warnings>"
        echo "# Total: $total_current warnings"
    } > "$BASELINE"
    sort "$WORK/current.txt" >> "$BASELINE"
    echo "baseline updated: $total_current warnings in $(wc -l < "$WORK/current.txt") files"
    exit 0
fi

if [ ! -f "$BASELINE" ]; then
    echo "docs/check-warnings.sh: baseline not found: $BASELINE" >&2
    echo "run 'docs/check-warnings.sh --update' to create it" >&2
    exit 1
fi

total_baseline=$(awk -F'\t' '!/^#/ { s += $2 } END { printf "%d", s + 0 }' "$BASELINE")

regressions=$(awk -F'\t' '
    NR == FNR { if ($0 !~ /^#/) { base[$1] = $2 }; next }
    {
        limit = base[$1] + 0
        if ($2 > limit) {
            printf "  %-45s %5d (baseline %d)\n", $1, $2, limit
            failed = 1
        }
    }
    END { exit failed ? 1 : 0 }
' "$BASELINE" "$WORK/current.txt") && status=0 || status=1

if [ "$status" -ne 0 ]; then
    echo "New doxygen warnings (more than the baseline):" >&2
    echo "$regressions" >&2
    echo >&2
    echo "Document the new members, or fix the markup, in this change." >&2
    echo "The baseline is $total_baseline warnings, the current tree produces $total_current." >&2
    exit 1
fi

echo "doxygen warnings: $total_current (baseline $total_baseline)"
if [ "$total_current" -lt "$total_baseline" ]; then
    echo "the tree is cleaner than the baseline: run 'docs/check-warnings.sh --update' and commit the result"
fi
