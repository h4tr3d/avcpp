std::string readTextFile(const fs::path &path)
{
    std::ifstream in(path);
    REQUIRE(in.is_open());
    std::ostringstream buffer;
    buffer << in.rdbuf();
    return buffer.str();
}

/**
 * Reads packet and frame counts for a single-stream fixture from manifest.json.
 *
 * The manifest is generated by generate.sh and has a fixed layout, so a light
 * positional scan is enough and keeps the tests free of a JSON dependency.
 */
FixtureCounts fixtureCounts(const std::string &file)
{
    auto const manifestPath = fs::path(AVCPP_TEST_DATA_DIR).parent_path() / "manifest.json";
    auto const manifest = readTextFile(manifestPath);

    auto const filePos = manifest.find("\"file\": \"" + file + "\"");
    REQUIRE(filePos != std::string::npos);

    auto const readNumber = [&](const char *key) -> long {
        auto pos = manifest.find(key, filePos);
        REQUIRE(pos != std::string::npos);
        pos = manifest.find(':', pos);
        REQUIRE(pos != std::string::npos);
        return std::stol(manifest.substr(pos + 1));
    };

    return {readNumber("\"packets\""), readNumber("\"frames\"")};
}

fs::path fixturePath(const std::string &file)
{
    // Manifest paths are relative to the repository root, while
    // AVCPP_TEST_DATA_DIR points at the media directory.
    auto const path = fs::path(AVCPP_TEST_DATA_DIR).parent_path() / file;
    REQUIRE(fs::exists(path));
    return path;
}

VideoStats decodeVideo(const std::string &file)
{
    std::error_code ec;

    av::FormatContext ictx;
    ictx.openInput(fixturePath(file).string(), ec);
    REQUIRE_FALSE(ec);
    ictx.findStreamInfo(ec);
    REQUIRE_FALSE(ec);

    av::Stream vst;
    for (auto &&st : ictx.streams()) {
        if (st.mediaType() == AVMEDIA_TYPE_VIDEO) {
            vst = st;
            break;
        }
    }
    REQUIRE(vst.isValid());

    av::VideoDecoderContext dec{vst};
    dec.open(ec);
    REQUIRE_FALSE(ec);

    VideoStats stats;
    av::Packet pkt;
    while ((pkt = ictx.readPacket(ec))) {
        if (pkt.streamIndex() != vst.index())
            continue;

        ++stats.packets;
        for (;;) {
            bool accepted = dec.send(pkt, ec);
            REQUIRE_FALSE(ec);

            for (;;) {
                auto frame = dec.receive(ec);
                REQUIRE_FALSE(ec);
                if (!frame.isValid())
                    break;

                CHECK(frame.isComplete());
                // Transfer to system memory must not lose the frame metadata.
                CHECK(frame.streamIndex() == vst.index());
                CHECK(frame.timeBase() != av::Rational());
                ++stats.frames;
            }

            if (accepted)
                break;
        }
    }
    REQUIRE_FALSE(ec);

    REQUIRE(dec.flush(ec));
    for (;;) {
        auto frame = dec.receive(ec);
        REQUIRE_FALSE(ec);
        if (!frame.isValid())
            break;
        ++stats.frames;
    }

    stats.eof = dec.isEof();
    return stats;
}

AudioStats decodeAudio(const std::string &file)
{
    std::error_code ec;

    av::FormatContext ictx;
    ictx.openInput(fixturePath(file).string(), ec);
    REQUIRE_FALSE(ec);
    ictx.findStreamInfo(ec);
    REQUIRE_FALSE(ec);

    av::Stream ast;
    for (auto &&st : ictx.streams()) {
        if (st.mediaType() == AVMEDIA_TYPE_AUDIO) {
            ast = st;
            break;
        }
    }
    REQUIRE(ast.isValid());

    av::AudioDecoderContext dec{ast};
    dec.open(ec);
    REQUIRE_FALSE(ec);

    AudioStats stats;
    av::Packet pkt;
    while ((pkt = ictx.readPacket(ec))) {
        if (pkt.streamIndex() != ast.index())
            continue;

        ++stats.packets;
        for (;;) {
            bool accepted = dec.send(pkt, ec);
            REQUIRE_FALSE(ec);

            for (;;) {
                auto samples = dec.receive(ec);
                REQUIRE_FALSE(ec);
                if (!samples.isValid())
                    break;

                CHECK(samples.isComplete());
                ++stats.frames;
                stats.samples += samples.samplesCount();
            }

            if (accepted)
                break;
        }
    }
    REQUIRE_FALSE(ec);

    REQUIRE(dec.flush(ec));
    for (;;) {
        auto samples = dec.receive(ec);
        REQUIRE_FALSE(ec);
        if (!samples.isValid())
            break;
        ++stats.frames;
        stats.samples += samples.samplesCount();
    }

    stats.eof = dec.isEof();
    return stats;
}

struct SubtitleStats
{
    long packets = 0;
    long frames = 0;
    std::vector<av::SubtitleFrame> subtitles;
};

SubtitleStats decodeSubtitles(const std::string &file)
{
    std::error_code ec;

    av::FormatContext ictx;
    ictx.openInput(fixturePath(file).string(), ec);
    REQUIRE_FALSE(ec);
    ictx.findStreamInfo(ec);
    REQUIRE_FALSE(ec);

    av::Stream sst;
    for (auto &&st : ictx.streams()) {
        if (st.mediaType() == AVMEDIA_TYPE_SUBTITLE) {
            sst = st;
            break;
        }
    }
    REQUIRE(sst.isValid());

    av::SubtitleDecoderContext dec{sst};
    dec.open(ec);
    REQUIRE_FALSE(ec);

    SubtitleStats stats;
    av::Packet pkt;
    while ((pkt = ictx.readPacket(ec))) {
        if (pkt.streamIndex() != sst.index())
            continue;

        ++stats.packets;

        size_t decodedBytes = 0;
        auto frame = dec.decode(pkt, 0, decodedBytes, ec);
        REQUIRE_FALSE(ec);
        CHECK(decodedBytes == pkt.size());

        if (!frame.isValid())
            continue;

        CHECK(frame.isComplete());
        ++stats.frames;
        stats.subtitles.emplace_back(std::move(frame));
    }
    REQUIRE_FALSE(ec);

    return stats;
}

struct HwVideoStats
{
    long packets = 0;
    long frames = 0;
    long hardwareFrames = 0;
    long softwareFrames = 0;
    bool eof = false;
};

av::Stream firstVideoStream(av::FormatContext &ictx)
{
    for (auto &&st : ictx.streams()) {
        if (st.mediaType() == AVMEDIA_TYPE_VIDEO)
            return st;
    }
    return {};
}

HwVideoStats decodeVideoHardware(const std::string &file,
                                 av::hw::DeviceType type,
                                 bool transferToSystem)
{
    std::error_code ec;

    av::FormatContext ictx;
    ictx.openInput(fixturePath(file).string(), ec);
    REQUIRE_FALSE(ec);
    ictx.findStreamInfo(ec);
    REQUIRE_FALSE(ec);

    av::Stream vst = firstVideoStream(ictx);
    REQUIRE(vst.isValid());

    av::Codec codec = av::hw::findDecoder(vst.codecParameters().codecId(), type);
    REQUIRE(codec.raw());

    av::hw::DeviceContext device = av::hw::DeviceContext::create(type, nullptr, {}, ec);
    REQUIRE(device.isValid());

    av::VideoDecoderContext dec{vst, codec};
    dec.setHwDeviceContext(device, ec);
    REQUIRE_FALSE(ec);
    dec.setHwTransferToSystem(transferToSystem);
    dec.open(av::Codec(), ec);
    REQUIRE_FALSE(ec);

    HwVideoStats stats;
    av::Packet pkt;
    while ((pkt = ictx.readPacket(ec))) {
        if (pkt.streamIndex() != vst.index())
            continue;

        ++stats.packets;
        for (;;) {
            bool accepted = dec.send(pkt, ec);
            REQUIRE_FALSE(ec);

            for (;;) {
                auto frame = dec.receive(ec);
                REQUIRE_FALSE(ec);
                if (!frame.isValid())
                    break;

                CHECK(frame.isComplete());
                // Transfer to system memory must not lose the frame metadata.
                CHECK(frame.streamIndex() == vst.index());
                CHECK(frame.timeBase() != av::Rational());
                ++stats.frames;
                if (frame.isHwFrame())
                    ++stats.hardwareFrames;
                else
                    ++stats.softwareFrames;
            }

            if (accepted)
                break;
        }
    }
    REQUIRE_FALSE(ec);

    REQUIRE(dec.flush(ec));
    for (;;) {
        auto frame = dec.receive(ec);
        REQUIRE_FALSE(ec);
        if (!frame.isValid())
            break;
        ++stats.frames;
        if (frame.isHwFrame())
            ++stats.hardwareFrames;
        else
            ++stats.softwareFrames;
    }

    stats.eof = dec.isEof();
    return stats;
}

av::VideoFrame decodeFirstHardwareFrame(const std::string &file,
                                        av::hw::DeviceType type)
{
    std::error_code ec;

    av::FormatContext ictx;
    ictx.openInput(fixturePath(file).string(), ec);
    REQUIRE_FALSE(ec);
    ictx.findStreamInfo(ec);
    REQUIRE_FALSE(ec);

    av::Stream vst = firstVideoStream(ictx);
    REQUIRE(vst.isValid());

    av::Codec codec = av::hw::findDecoder(vst.codecParameters().codecId(), type);
    REQUIRE(codec.raw());

    av::hw::DeviceContext device = av::hw::DeviceContext::create(type, nullptr, {}, ec);
    REQUIRE(device.isValid());

    av::VideoDecoderContext dec{vst, codec};
    dec.setHwDeviceContext(device, ec);
    REQUIRE_FALSE(ec);
    dec.open(av::Codec(), ec);
    REQUIRE_FALSE(ec);

    // Only the first frame is needed. Keeping every hardware frame alive
    // exhausts the decoder surface pool on FFmpeg 4.x CUDA.
    auto firstHardwareFrame = [&]() -> av::VideoFrame {
        for (;;) {
            auto frame = dec.receive(ec);
            REQUIRE_FALSE(ec);
            if (!frame.isValid())
                return {};
            if (frame.isHwFrame())
                return frame;
        }
    };

    av::Packet pkt;
    while ((pkt = ictx.readPacket(ec))) {
        if (pkt.streamIndex() != vst.index())
            continue;

        for (;;) {
            bool accepted = dec.send(pkt, ec);
            REQUIRE_FALSE(ec);

            av::VideoFrame frame = firstHardwareFrame();
            if (frame.isValid())
                return frame;

            if (accepted)
                break;
        }
    }
    REQUIRE_FALSE(ec);

    REQUIRE(dec.flush(ec));
    return firstHardwareFrame();
}

